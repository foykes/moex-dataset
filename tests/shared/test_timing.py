"""Bounded synthetic telemetry oracles; no native/default-command launch.

These nodes also run inside default-command probes. Raw decoder and identity fixtures add no process launch. No recursion exemption or
skip is needed: original fixtures use32records; raw capacity fixture uses384records/24640B.
"""

import io

import pytest
import mds_offline_guard as guard


def _identity():
    return dict(run_id='1' * 32, lane='f3', role='command', ticket_id='2' * 32,
                tested_sha='3' * 40, source_digest='4' * 64, pid=123, creation_100ns=456)


def _records():
    return [dict(_identity(), seq=n, mono_ns=n * 10, event=event, value=0, phase=0)
            for n, event in enumerate(('bootstrap', 'start_written', 'final_end', 'writer_end'), 1)]


def _child_fixture():
    # Literal OS observations are independent of the launch claim. Neither the
    # expected parent edge nor expected errors are generated by the validator.
    context = dict(run_id='1' * 32, lane='f3', tested_sha='3' * 40,
                   source_digest='4' * 64)
    ticket = dict(context, ticket_id='5' * 32, parent_id='2' * 32, profile=1)
    launch = dict(context, child_id='5' * 32, issuer_id='2' * 32,
                  child_pid=234, child_creation_100ns=600, child_parent_pid=123)
    issuer = dict(context, ticket_id='2' * 32, pid=123,
                  creation_100ns=456, exit_100ns=1000)
    observed = dict(pid=234, creation_100ns=600, parent_pid=123,
                    exit_100ns=900, image='pytest', image_bound=True)
    interpreter = dict(pid=345, creation_100ns=650, parent_pid=234,
                       exit_100ns=850, image='runtime', image_bound=True)
    return ticket, launch, issuer, observed, interpreter


def test_timing_identity_binds_run_lane_role_sha():
    records = _records()
    required = {'bootstrap', 'start_written', 'final_end', 'writer_end'}
    assert guard.timing_trace_errors(records, _identity(), required, 40) == []
    for key in guard._TIMING_ID_KEYS:
        foreign = [dict(row) for row in records]
        foreign[0][key] = 999 if key in {'pid', 'creation_100ns'} else 'FOREIGN'
        assert 'FOREIGN' in guard.timing_trace_errors(foreign, _identity(), required, 40), key
    ticket, launch, issuer, observed, interpreter = _child_fixture()
    assert guard.timing_child_errors(ticket, launch, issuer, [observed]) == []
    assert guard.timing_child_errors(ticket, launch, issuer, [observed], interpreter) == []
    for changed in ({'child_id': '6' * 32}, {'issuer_id': '6' * 32},
                    {'run_id': '6' * 32}, {'tested_sha': '6' * 40},
                    {'source_digest': '6' * 64}):
        assert 'FOREIGN_CHILD' in guard.timing_child_errors(
            ticket, {**launch, **changed}, issuer, [observed])
    for changed in ({'pid': 999}, {'creation_100ns': 601}, {'parent_pid': 999}):
        assert 'FOREIGN_IDENTITY' in guard.timing_child_errors(
            ticket, launch, issuer, [{**observed, **changed}])
    # Agreement between two claims does not establish the real parent edge.
    assert 'ACTUAL_PARENT' in guard.timing_child_errors(ticket,
        dict(launch, child_parent_pid=999), issuer, [dict(observed, parent_pid=999)])
    assert 'ACTUAL_PARENT' in guard.timing_child_errors(ticket, launch,
        dict(issuer, creation_100ns=700), [observed])  # PID recycled after launch.
    assert 'ACTUAL_PARENT' in guard.timing_child_errors(ticket, launch,
        dict(issuer, exit_100ns=599), [observed])
    assert 'FOREIGN_CHILD' in guard.timing_child_errors(ticket, launch,
        dict(issuer, ticket_id='6' * 32), [observed])  # Sibling, not issuer.
    for changed in ({'parent_pid': 123}, {'image': 'other'}, {'image_bound': False},
                    {'creation_100ns': 901}):
        assert 'CONSOLE_WRAPPER' in guard.timing_child_errors(
            ticket, launch, issuer, [observed], {**interpreter, **changed})
    assert 'CONSOLE_WRAPPER' in guard.timing_child_errors(
        dict(ticket, profile=2), launch, issuer, [observed], interpreter)
    # A non-profile Python issuer and its ordinary native Git child have the
    # same identity requirements; a detailed command stream is not an oracle.
    native_ticket = dict(ticket, profile=0, native=True, role='native-git')
    native_issuer = dict(issuer, role='f3-control')
    native_child = dict(observed, image='git', image_bound=True)
    assert guard.timing_child_errors(native_ticket, launch, native_issuer, [native_child]) == []
    assert guard.timing_child_errors(native_ticket, launch, native_issuer, []) == ['MISSING_IDENTITY']
    assert 'ACTUAL_PARENT' in guard.timing_child_errors(native_ticket, launch,
        dict(native_issuer, exit_100ns=599), [native_child])
    assert 'FOREIGN_IDENTITY' in guard.timing_child_errors(native_ticket, launch,
        native_issuer, [dict(native_child, creation_100ns=601)])
    assert guard.timing_auxiliary('f3-control', 0)
    assert guard.timing_auxiliary('f2-probe', 0)
    assert guard.timing_auxiliary('command', 0)
    for role, profile in (('supervisor', 0), ('lane-worker', 4),
                          ('command', 1), ('command', 2), ('command', 3), ('FOREIGN', 0)):
        assert not guard.timing_auxiliary(role, profile)


def test_timing_trace_rejects_missing_corrupt_or_foreign_records():
    required = {'bootstrap', 'start_written', 'final_end', 'writer_end'}
    original = _records()
    cases = [
        (original[:-1], 'MISSING'),
        ([None, *original[1:]], 'CORRUPT'),
        ([*original[:2], dict(original[2], tested_sha='a' * 40), original[3]], 'FOREIGN'),
        ([*original[:3], dict(original[3], mono_ns=41)], 'LATE'),
        ([*original, original[-1]], 'DUPLICATE'),
        ([dict(original[0], seq=[]), *original[1:]], 'CORRUPT'),
    ]
    for records, expected in cases:
        assert expected in guard.timing_trace_errors(records, _identity(), required, 40)
    assert _records() == original  # The oracle does not repair/normalize input.
    ticket, launch, issuer, observed, _ = _child_fixture()
    # Complete native receipts/five writers cannot replace a missed short child.
    assert guard.timing_child_errors(ticket, launch, issuer, []) == ['MISSING_IDENTITY']
    assert guard.timing_child_errors(ticket, launch, issuer,
        [observed, observed]) == ['AMBIGUOUS_IDENTITY']
    identity = dict(_identity(), issued_children={ticket['ticket_id']: ticket})
    assert 'MISSING_CHILD' in guard.timing_trace_errors(original, identity, required, 40)
    child_records = [dict(row) for row in original]
    child_records[0].update(event='ticket_issued', child_id='5' * 32, issuer_id='2' * 32)
    child_records[1].update(event='child_launch', **{key: value for key, value in launch.items()
        if key.startswith('child_') or key == 'issuer_id'})
    child_required = {'ticket_issued', 'child_launch', 'final_end', 'writer_end'}
    assert guard.timing_trace_errors(child_records, identity, child_required, 40) == []
    for field in ('child_id', 'issuer_id'):
        missing = [dict(row) for row in child_records]
        missing[1].pop(field)
        assert 'FOREIGN_CHILD' in guard.timing_trace_errors(missing, identity, child_required, 40)
    stale = [dict(row) for row in child_records]
    stale[1]['child_id'] = '6' * 32
    assert 'FOREIGN_CHILD' in guard.timing_trace_errors(stale, identity, child_required, 40)
    duplicate = [*child_records, dict(child_records[1], seq=5, mono_ns=40)]
    assert 'DUPLICATE_CHILD' in guard.timing_trace_errors(duplicate, identity, child_required, 40)
    second = dict(ticket, ticket_id='6' * 32)
    two_children = dict(_identity(), issued_children={'5' * 32: ticket, '6' * 32: second})
    alias = [*child_records[:2], dict(child_records[0], child_id='6' * 32),
             dict(child_records[1], child_id='6' * 32), *child_records[2:]]
    alias = [dict(row, seq=n, mono_ns=n * 10) for n, row in enumerate(alias, 1)]
    assert 'REUSED_CHILD_IDENTITY' in guard.timing_trace_errors(alias, two_children, child_required, 60)
    distinct = [dict(row) for row in alias]
    distinct[3].update(child_pid=235, child_creation_100ns=700)
    assert guard.timing_trace_errors(distinct, two_children, child_required, 60) == []


def test_timing_result_cannot_override_native_failure():
    # Original outward failure codes remain independent, including a logical
    # pytest success followed by a native timeout/guard failure.
    ticket, launch, issuer, observed, _ = _child_fixture()
    for native in (0, 86, 124, 1, 'NOT_AVAILABLE'):
        for valid in (True, False):
            result = guard.timing_verdict(native, valid=valid)
            assert result['NATIVE_VERDICT'] == native
            assert result['DIAGNOSTIC_VERDICT'] == ('COMPLETE' if valid else 'INVALID')
        for external in ([], [dict(observed, creation_100ns=601)], [observed, observed]):
            valid = not guard.timing_child_errors(ticket, launch, issuer, external)
            assert guard.timing_verdict(native, valid=valid) == {
                'NATIVE_VERDICT': native, 'DIAGNOSTIC_VERDICT': 'INVALID'}
    assert guard.timing_verdict(0, valid=False) == {
        'NATIVE_VERDICT': 0, 'DIAGNOSTIC_VERDICT': 'INVALID'}


def test_timing_budget_boundaries_and_abort_use_fake_clock():
    # Exact nanoseconds from a recorded fake clock; no real sleep or performance test.
    stamps = iter((10, 1000000010, 10, 1000000011))
    start = next(stamps)
    elapsed = next(stamps) - start
    boundary = dict(cpu_percent=1, rss_bytes=134217728, sync_ns=elapsed,
                    telemetry_bytes=4194304)
    assert guard.timing_verdict(86, **boundary)['DIAGNOSTIC_VERDICT'] == 'COMPLETE'
    start = next(stamps)
    over = next(stamps) - start
    for changed in ({'cpu_percent': 1.000001}, {'rss_bytes': 134217729},
                    {'sync_ns': over}, {'telemetry_bytes': 4194305}):
        result = guard.timing_verdict(86, **{**boundary, **changed})
        assert result == {'NATIVE_VERDICT': 86, 'DIAGNOSTIC_VERDICT': 'ABORTED'}
    sink = io.BytesIO()
    assert guard.timing_store(sink, b'1234', 0, 4) == 4
    with pytest.raises(ValueError, match='TIMING_BYTES'):
        guard.timing_store(sink, b'5', 4, 4)
    assert sink.getvalue() == b'1234'
    # Five original detailed streams, finite AUX pool, observer, all new
    # metadata and one eight-byte abort marker per stream share exactly 4 MiB.
    assert guard._TIMING_WRITER_BYTES == 524280
    assert guard._TIMING_AUX_BYTES == 8184
    assert (5 * guard._TIMING_WRITER_BYTES + 32 * guard._TIMING_AUX_BYTES
            + 1048576 + 262144 + 37 * 8) == 4194304


def test_timing_storage_failure_is_not_complete():
    class Refusal:
        def write(self, payload):
            raise OSError('synthetic refusal')

    class ShortWrite:
        def write(self, payload):
            return len(payload) - 1

    for store in (Refusal(), ShortWrite()):
        with pytest.raises(OSError):
            guard.timing_store(store, b'fixture', 0, 4096)
        assert guard.timing_verdict(0, stored=False) == {
            'NATIVE_VERDICT': 0, 'DIAGNOSTIC_VERDICT': 'ABORTED'}
    # These are original communicate-return buffers, not an encoding of text or
    # an invented empty stream. The numeric outcomes are independent literals.
    pair = (b'F3_NATIVE_STDOUT\x00\xff', b'')
    assert guard.timing_buffer_phase(*pair) == 1
    assert guard.timing_buffer_phase(b'', b'') == 1
    assert guard.timing_buffer_phase(*pair, previous=pair) == 1
    assert guard.timing_buffer_phase(None, b'') == 2
    assert guard.timing_buffer_phase(b'', None) == 2
    assert guard.timing_buffer_phase('decoded stdout', '') == 3
    assert guard.timing_buffer_phase(*pair, complete=False) == 4
    assert guard.timing_buffer_phase(*pair, previous=(b'other bytes', b'')) == 6
    for values in ((None, b''), ('decoded stdout', ''), (b'', None)):
        assert guard.timing_verdict(0, valid=guard.timing_buffer_phase(*values) == 1) == {
            'NATIVE_VERDICT': 0, 'DIAGNOSTIC_VERDICT': 'INVALID'}
    # Independently recorded SHA-256 literals for b'abc' and empty stderr.
    # A fresh seal of substituted/truncated retained bytes cannot replace the
    # original sole-reader witness, even when both files still exist.
    expected = dict(event='native_buffers', value=1, phase=1, child_id='5' * 32,
        stdout_bytes=3, stderr_bytes=0,
        stdout_sha256='ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad',
        stderr_sha256='e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855')
    retained = {key: value for key, value in expected.items()
                if key not in {'event', 'value', 'phase'}}
    assert guard.timing_buffer_binding_errors(expected, retained) == []
    for changed in ({'stdout_bytes': 2}, {'stderr_bytes': 1},
                    {'stdout_sha256': '0' * 64}, {'stderr_sha256': '0' * 64}):
        assert guard.timing_buffer_binding_errors(expected, {**retained, **changed}) == [
            'BUFFER_BINDING_MISMATCH']
    assert guard.timing_buffer_binding_errors(expected, dict(retained, child_id='6' * 32)) == [
        'FOREIGN_BUFFER_BINDING']
    assert guard.timing_buffer_binding_errors(dict(expected, stdout_bytes=None), retained) == [
        'CORRUPT']
    assert guard.timing_buffer_binding_errors(
        {key: value for key, value in expected.items() if key != 'stdout_sha256'}, retained) == [
            'MISSING_BUFFER_BINDING']


def test_timing_public_report_excludes_synthetic_private_values():
    record = dict(_records()[0], argv='F3_SYNTHETIC_SECRET',
                  private_path='C:/synthetic/private', environment={'TOKEN': 'SYNTHETIC'},
                  exception='SYNTHETIC_EXCEPTION_PAYLOAD', stdout='RAW_SYNTHETIC_OUTPUT')
    public = guard.timing_public(record)
    assert public == _records()[0]
    assert all(value not in str(public) for value in (
        'F3_SYNTHETIC_SECRET', 'C:/synthetic/private', 'TOKEN',
        'SYNTHETIC_EXCEPTION_PAYLOAD', 'RAW_SYNTHETIC_OUTPUT'))
    malformed = dict(record, value='SYNTHETIC_PRIVATE_VALUE', role='C:/synthetic/private')
    assert 'value' not in guard.timing_public(malformed)
    assert 'role' not in guard.timing_public(malformed)
    binding = dict(record, child_id='PRIVATE_CHILD_CANARY', issuer_id='PRIVATE_ISSUER_CANARY',
                   child_pid='PRIVATE_PID_CANARY', child_parent_pid='PRIVATE_PARENT_CANARY')
    projected = guard.timing_public(binding)
    assert all(value not in str(projected) for value in (
        'PRIVATE_CHILD_CANARY', 'PRIVATE_ISSUER_CANARY', 'PRIVATE_PID_CANARY', 'PRIVATE_PARENT_CANARY'))
    auxiliary = dict(record, role='f3-control', event='native_buffers', value=1, phase=1)
    projected = guard.timing_public(auxiliary)
    assert projected['role'] == 'f3-control'
    assert projected['event'] == 'native_buffers'
    assert all(value not in str(projected) for value in (
        'F3_SYNTHETIC_SECRET', 'C:/synthetic/private', 'TOKEN', 'RAW_SYNTHETIC_OUTPUT'))


def _raw_reservation_decoder():
    # Extract the actual pure nested decoder; never call the native writer here.
    import ast
    import hashlib
    import inspect
    import textwrap
    tree = ast.parse(textwrap.dedent(inspect.getsource(guard._timing_raw_reserve)))
    nodes = [node for node in ast.walk(tree)
             if isinstance(node, ast.FunctionDef) and node.name == 'decode']
    assert len(nodes) == 1
    namespace = {'hashlib': hashlib}
    exec(compile(ast.Module(body=nodes, type_ignores=[]), 'timing-raw-pure', 'exec'), namespace)
    return namespace['decode']


def _raw_capacity_fixture():
    import hashlib
    header = b'H' * 64
    snapshot = (b'\0' * 16 + (16777216).to_bytes(8, 'little') + b'\0' * 8
                + hashlib.sha256(b'MDSRAW-SNAPSHOT-2\0' + header).digest())
    return header, snapshot


def test_timing_raw_ledger_preserves_budget_and_snapshot_capacity():
    decode = _raw_reservation_decoder()
    header, snapshot = _raw_capacity_fixture()
    row = bytes.fromhex('2' * 32) + (50331648).to_bytes(8, 'little') + b'\0' * 8 + b'P' * 32
    seen, used = decode(header + snapshot + row, header, {'2' * 32})
    assert seen == {'0' * 32, '2' * 32}
    assert used == 67108864
    overflow = row[:16] + (50331649).to_bytes(8, 'little') + row[24:]
    with pytest.raises(ValueError, match='^RAW_BUDGET$'):
        decode(header + snapshot + overflow, header, {'2' * 32})


def test_timing_raw_ledger_rejects_foreign_duplicate_and_partial_records():
    decode = _raw_reservation_decoder()
    header, snapshot = _raw_capacity_fixture()
    row = bytes.fromhex('2' * 32) + (3).to_bytes(8, 'little') + b'\0' * 8 + b'P' * 32
    cases = [(header + snapshot + row + row, header, {'2' * 32}, 'RAW_DUPLICATE'),
             (header + snapshot + row, header, set(), 'RAW_FOREIGN'),
             (header + snapshot + b'x', header, set(), 'RAW_LEDGER'),
             (header, header, set(), 'RAW_SNAPSHOT_RESERVATION'),
             (b'X' + header[1:] + snapshot, header, set(), 'RAW_LEDGER')]
    for raw, binding, allowed, error in cases:
        with pytest.raises(ValueError, match='^' + error + '$'):
            decode(raw, binding, allowed)


def test_timing_raw_snapshot_reservation_is_immutable():
    decode = _raw_reservation_decoder()
    header, snapshot = _raw_capacity_fixture()
    for changed in (snapshot[:16] + (16777215).to_bytes(8, 'little') + snapshot[24:],
                    snapshot[:-1] + bytes([snapshot[-1] ^ 1])):
        with pytest.raises(ValueError, match='^RAW_FOREIGN$'):
            decode(header + changed, header, set())


def test_timing_raw_ledger_has_finite_record_capacity():
    decode = _raw_reservation_decoder()
    header, snapshot = _raw_capacity_fixture()
    ids = {n.to_bytes(16, 'big').hex() for n in range(1, 384)}
    rows = b''.join(bytes.fromhex(identifier) + b'\0' * 16 + b'P' * 32
                    for identifier in sorted(ids))
    seen, used = decode(header + snapshot + rows, header, ids)
    assert len(seen) == 384 and used == 16777216
    with pytest.raises(ValueError, match='^RAW_LEDGER$'):
        decode(header + snapshot + rows + b'\0' * 64, header, ids)


def _raw_identity_validator():
    # Same actual pure decision used before any Win32 ledger write.
    import ast
    import inspect
    import textwrap
    tree = ast.parse(textwrap.dedent(inspect.getsource(guard._timing_raw_reserve)))
    nodes = [node for node in ast.walk(tree)
             if isinstance(node, ast.FunctionDef) and node.name == 'validate_identity']
    assert len(nodes) == 1
    namespace = {}
    exec(compile(ast.Module(body=nodes, type_ignores=[]), 'timing-file-identity-pure', 'exec'), namespace)
    return namespace['validate_identity']


def test_timing_raw_file_requires_exact_expected_os_identity():
    validate = _raw_identity_validator()
    identity = b'I' * 20
    assert validate((identity, 128), identity) == 128
    assert validate((identity, 24640), identity) == 24640
    for actual, expected in ((None, identity), ((b'F' * 20, 128), identity),
                             ((identity, 128), None), ((identity, 128), b'')):
        with pytest.raises(ValueError, match='^RAW_REPLACED$'):
            validate(actual, expected)


def test_timing_raw_file_identity_does_not_waive_ledger_length():
    validate = _raw_identity_validator()
    for length in (127, 24641, True, 128.0):
        with pytest.raises(ValueError, match='^RAW_LEDGER$'):
            validate((b'I' * 20, length), b'I' * 20)
